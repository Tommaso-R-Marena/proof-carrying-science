#!/usr/bin/env python3
"""Generate a theorem inventory from Lean sources (name + path + heuristic status)."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEAN = ROOT / "lean"
OUT = ROOT / "docs" / "THEOREM_INVENTORY.md"

THEOREM_RE = re.compile(r"^(theorem|lemma)\s+(\S+)", re.M)
SORRY_RE = re.compile(r"\bsorry\b|\badmit\b")


def main() -> None:
    rows = []
    for path in sorted(LEAN.rglob("*.lean")):
        text = path.read_text()
        has_sorry = bool(SORRY_RE.search(text))
        for m in THEOREM_RE.finditer(text):
            kind, name = m.group(1), m.group(2)
            rows.append(
                {
                    "name": name.rstrip(":"),
                    "kind": kind,
                    "path": str(path.relative_to(ROOT)),
                    "sorry_in_file": has_sorry,
                }
            )
    lines = [
        "# Theorem inventory (CertNum)",
        "",
        "Generated by `scripts/gen_theorem_inventory.py`.",
        "",
        "| Name | Kind | Path | File contains sorry? |",
        "|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['name']}` | {r['kind']} | `{r['path']}` | {r['sorry_in_file']} |"
        )
    lines += [
        "",
        f"Total theorems/lemmas: **{len(rows)}**",
        "",
        "Axiom policy: no project axioms; Mathlib classical foundations only.",
        "Soundness-critical: `mem_neg`, `mem_add`, `mem_sub`, `mem_mul`, hull/inter theorems.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
