"""Explicit scientific reasoning states — never collapsed to PASS/FAIL."""

from __future__ import annotations

from enum import Enum


class ScientificStatus(str, Enum):
    IDENTIFIED_UNDER_ASSUMPTIONS = "IDENTIFIED_UNDER_ASSUMPTIONS"
    PARTIALLY_IDENTIFIED = "PARTIALLY_IDENTIFIED"
    NOT_IDENTIFIABLE = "NOT_IDENTIFIABLE"
    ESTIMATED_WITH_UNCERTAINTY = "ESTIMATED_WITH_UNCERTAINTY"
    ASSUMPTION_VIOLATION_DETECTED = "ASSUMPTION_VIOLATION_DETECTED"
    EMPIRICALLY_INCONCLUSIVE = "EMPIRICALLY_INCONCLUSIVE"
    EXPERIMENT_PROPOSED = "EXPERIMENT_PROPOSED"
    MODEL_REFUTED = "MODEL_REFUTED"
    OPEN = "OPEN"
    UNSUPPORTED = "UNSUPPORTED"
