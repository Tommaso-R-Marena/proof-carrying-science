"""A memory limit for each Lean process of the prospective run (protocol 6 step 4, criterion C7).

The frozen v1 kernel call (``claimcheck_v1.lean.check_source``) runs ``PCS_CLAIMCHECK_LEAN`` (or
``lean`` on PATH) with a reduced environment and sets no memory limit.  ``make_guarded_lean`` writes
a small executable that the operator names in ``PCS_CLAIMCHECK_LEAN``.  It runs the real Lean with
the same arguments, measures its resident memory every ``poll_seconds``, stops it with SIGKILL
when it exceeds the limit, and passes its output and exit status through unchanged.  A stopped
process exits non-zero, so the frozen code records "Lean rejected the obligation" and the claim is
UNKNOWN (fail closed).  Every run is appended to a JSON-lines log: obligation digest, seconds, peak
resident memory (``ru_maxrss`` of the child) and whether the limit stopped it.  That log is where
C7 takes peak memory from.  Linux only (it reads /proc); elsewhere it refuses to run.

Nothing in v1 is changed.  Tested with a synthetic stand-in for Lean (``tests/test_lean_guard.py``).
"""
from __future__ import annotations

import json
import stat
import sys
from pathlib import Path

TEMPLATE = r'''#!{python}
# Generated by research/claimcheck_v1_1/prospective/lean_guard.py.  Configuration is embedded
# because the frozen kernel call runs this with a reduced environment.
import hashlib, json, os, resource, signal, subprocess, sys, tempfile, time
CONFIG = {config}

def rss_kb(pid):
    try:
        with open(f"/proc/{{pid}}/status", encoding="ascii") as fh:
            for line in fh:
                if line.startswith("VmRSS:"):
                    return int(line.split()[1])
    except (FileNotFoundError, ProcessLookupError):
        return 0
    return 0

def main(argv):
    if not os.path.isdir("/proc"):
        sys.stderr.write("lean guard: /proc is not available; refusing to run without a memory limit\n")
        return 2
    limit_kb = CONFIG["memory_limit_mb"] * 1024
    target = next((a for a in argv if a.endswith(".lean")), None)
    digest = None
    if target and os.path.isfile(target):
        with open(target, "rb") as fh:
            digest = hashlib.sha256(fh.read()).hexdigest()
    with tempfile.TemporaryFile() as out, tempfile.TemporaryFile() as err:
        start = time.monotonic()
        child = subprocess.Popen([CONFIG["real_lean"], *argv], stdout=out, stderr=err)
        killed = False
        while child.poll() is None:
            if rss_kb(child.pid) > limit_kb:
                child.send_signal(signal.SIGKILL)
                child.wait()
                killed = True
                break
            time.sleep(CONFIG["poll_seconds"])
        seconds = time.monotonic() - start
        peak_kb = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
        out.seek(0)
        err.seek(0)
        sys.stdout.buffer.write(out.read())
        sys.stdout.flush()
        sys.stderr.buffer.write(err.read())
        if killed:
            sys.stderr.write(f"lean guard: memory limit of {{CONFIG['memory_limit_mb']}} MB exceeded; process stopped\n")
        sys.stderr.flush()
    record = {{"time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "obligation_sha256": digest,
              "argv": [os.path.basename(a) for a in argv], "seconds": round(seconds, 3), "peak_rss_mb": round(peak_kb / 1024, 1),
              "memory_limit_mb": CONFIG["memory_limit_mb"], "stopped_for_memory": killed,
              "exit": 137 if killed else child.returncode}}
    with open(CONFIG["log"], "a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, sort_keys=True) + "\n")
        fh.flush()
        os.fsync(fh.fileno())
    return 137 if killed else child.returncode

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
'''


def make_guarded_lean(directory: Path, real_lean: str, memory_limit_mb: int, log_path: Path, *, poll_seconds: float = 0.05) -> Path:
    """Write the guard executable into ``directory`` and return its path (for PCS_CLAIMCHECK_LEAN)."""
    if memory_limit_mb <= 0:
        raise ValueError("memory limit must be positive")
    config = {"real_lean": str(Path(real_lean).resolve()), "memory_limit_mb": int(memory_limit_mb),
              "log": str(Path(log_path).resolve()), "poll_seconds": float(poll_seconds)}
    path = Path(directory) / "lean-guarded"
    path.write_text(TEMPLATE.format(python=sys.executable, config=json.dumps(config)), encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def read_log(path: Path) -> list[dict]:
    path = Path(path)
    return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()] if path.exists() else []
